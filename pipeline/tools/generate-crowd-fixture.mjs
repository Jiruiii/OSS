#!/usr/bin/env node
// Generates fixtures/crowd-reports-v0.json and its byte-identical copy under
// android/app/src/test/resources/fixtures/, so the Node contract and the
// Kotlin EventVerifier / CrowdChunkCodec are checked against the same bytes.
//
// Keys come from fixed seeds so re-running produces the same fixture. These
// private keys exist ONLY for this fixture; never trust them anywhere else.
//
//   node pipeline/tools/generate-crowd-fixture.mjs

import { createPrivateKey, createPublicKey } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildAttestation } from '../lib/attest.mjs';
import { signCanonical } from '../lib/crypto.mjs';
import { chunkSignatureInput } from '../lib/canonical.mjs';
import { signEvent, verifyEvent } from '../lib/contract.mjs';
import { buildCrowdChunk, buildCrowdReport, verifyCrowdChunk } from '../lib/crowd-report.mjs';
import { deviceKeyIdForPublicKey, publicKeySpkiBase64 } from '../lib/device-key.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const PKCS8_ED25519_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex');

function keyPairFromSeed(label) {
  const seed = Buffer.alloc(32);
  Buffer.from(label, 'utf8').copy(seed);
  const privateKey = createPrivateKey({ key: Buffer.concat([PKCS8_ED25519_PREFIX, seed]), format: 'der', type: 'pkcs8' });
  return { privateKey, publicKey: createPublicKey(privateKey) };
}

const NOW = '2026-09-24T01:00:00Z';
const ISSUED_AT = new Date('2026-09-24T00:30:00Z');
const deviceA = keyPairFromSeed('crowd-fixture-device-a');
const deviceB = keyPairFromSeed('crowd-fixture-device-b');
const official = keyPairFromSeed('crowd-fixture-official');
const OFFICIAL_KEY_ID = 'crowd-fixture-official-2026';

const report = buildCrowdReport({
  category: 'ROAD_BLOCKAGE',
  description: '成功路二段落石，單線通行',
  lon: 121.590304,
  lat: 25.083506,
  locationSource: 'MAP_PICK',
  locationHint: { method: 'ADDRESS', query: '內湖區成功路', label: '成功路', kind: 'ROAD', precision: 'ROAD' },
  issuedAt: ISSUED_AT,
  reportUuid: '00000000-0000-4000-8000-000000000001',
  privateKey: deviceA.privateKey,
  publicKey: deviceA.publicKey,
});

const tampered = structuredClone(report);
tampered.attributes.description = '成功路二段完全封閉';

// Signed by device A, but advertises device B's public key: the key id no
// longer matches the fingerprint of the embedded key.
const fingerprintMismatch = { ...report, signer_public_key: publicKeySpkiBase64(deviceB.publicKey) };

// A device key trying to publish into an official namespace.
const officialImpostor = signEvent({
  ...structuredClone(report),
  namespace: 'official.tdx',
  event_id: 'road:impostor-001',
  event_type: 'ROAD_STATUS',
  attributes: { status: 'CLOSED', area_id: 'crowd', theme: 'road' },
}, deviceA.privateKey);

const { signer_public_key: _dropped, ...missingSignerKey } = report;

const validChunk = buildCrowdChunk(report, deviceA.privateKey);
const relayTamperedChunk = structuredClone(validChunk);
relayTamperedChunk.events[0].attributes.description = '已由中繼節點改寫';

// Device B re-wraps A's report and signs the chunk with its own key.
const resignedChunk = { ...structuredClone(validChunk), signing_key_id: deviceKeyIdForPublicKey(deviceB.publicKey) };
resignedChunk.signature = signCanonical(chunkSignatureInput(resignedChunk), deviceB.privateKey);

const attestationConfirmed = buildAttestation({
  report,
  verdict: 'CONFIRMED',
  privateKey: official.privateKey,
  keyId: OFFICIAL_KEY_ID,
  issuedAt: new Date('2026-09-24T00:50:00Z'),
});
const attestationRefuted = buildAttestation({
  report,
  verdict: 'REFUTED',
  privateKey: official.privateKey,
  keyId: OFFICIAL_KEY_ID,
  issuedAt: new Date('2026-09-24T00:55:00Z'),
  previous: attestationConfirmed,
});

const fixture = {
  schema_version: 'crowd-fixture-v0',
  description: 'Generated by pipeline/tools/generate-crowd-fixture.mjs. Keys are fixture-only seeds; never trust them outside tests.',
  now: NOW,
  device_key_id: report.signing_key_id,
  official_key_id: OFFICIAL_KEY_ID,
  official_public_key: publicKeySpkiBase64(official.publicKey),
  event_cases: [
    { name: 'valid_report', expect: { valid: true, state: 'unverified' }, event: report },
    { name: 'tampered_attributes', expect: { valid: false, stage: 'integrity' }, event: tampered },
    { name: 'fingerprint_mismatch', expect: { valid: false, stage: 'trust' }, event: fingerprintMismatch },
    { name: 'device_key_official_namespace', expect: { valid: false, stage: 'trust' }, event: officialImpostor },
    { name: 'missing_signer_public_key', expect: { valid: false, stage: 'schema' }, event: missingSignerKey },
  ],
  chunk_cases: [
    { name: 'valid_chunk', expect: { valid: true }, chunk: validChunk },
    { name: 'relay_tampered', expect: { valid: false, error: 'chunk_hash_mismatch' }, chunk: relayTamperedChunk },
    { name: 'relay_resigned', expect: { valid: false, error: 'crowd_chunk_signer_mismatch' }, chunk: resignedChunk },
  ],
  attestations: [attestationConfirmed, attestationRefuted],
};

// Self-check before writing, so a broken generator cannot ship a fixture that
// disagrees with the contract it is meant to pin.
const trusted = { trustedKeyIds: [OFFICIAL_KEY_ID], now: NOW };
for (const testCase of fixture.event_cases) {
  const result = verifyEvent(testCase.event, official.publicKey, trusted);
  if (result.valid !== testCase.expect.valid || (!result.valid && result.stage !== testCase.expect.stage)) {
    throw new Error(`${testCase.name}: expected ${JSON.stringify(testCase.expect)}, got ${JSON.stringify(result)}`);
  }
}
for (const testCase of fixture.chunk_cases) {
  const result = verifyCrowdChunk(testCase.chunk, { now: NOW });
  if (result.valid !== testCase.expect.valid || (!result.valid && result.errors[0] !== testCase.expect.error)) {
    throw new Error(`${testCase.name}: expected ${JSON.stringify(testCase.expect)}, got ${JSON.stringify(result)}`);
  }
}

const text = `${JSON.stringify(fixture, null, 2)}\n`;
const targets = [
  path.join(ROOT, 'fixtures/crowd-reports-v0.json'),
  path.join(ROOT, 'android/app/src/test/resources/fixtures/crowd-reports-v0.json'),
];
for (const target of targets) {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, text, 'utf8');
}
console.log(`wrote:\n${targets.map((target) => `  ${target}`).join('\n')}`);
