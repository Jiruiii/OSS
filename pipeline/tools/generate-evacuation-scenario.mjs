#!/usr/bin/env node
// Replayable evacuation-routing demo (docs/superpowers/plans/2026-09-24-evacuation-routing.md Task 7).
//
//   1. A person in 西湖 plans a route; the best shelter is 西湖國小.
//   2. A ROAD_STATUS CLOSED event for OSM way 1462339230 arrives over the mesh;
//      the route to 西湖國小 detours around it.
//   3. A SHELTER_STATUS event says 西湖國小 is full; the recommendation moves
//      to 西湖國中.
//
// The events are SYNTHETIC (every one says so in attributes.synthetic_notice)
// on top of real OSM geometry. Each step is its own signed chunk-v0 dataset so a
// node can receive step 3 without step 2, and the trust key is added to (not
// replacing) both copies of trust/trusted-keys.json, following
// generate-peer-sync-priority-chunks-fixture.mjs. The private key is discarded.
//
//   node pipeline/tools/generate-evacuation-scenario.mjs

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildBundle } from '../lib/bundle.mjs';
import { signEvent, verifyChunk } from '../lib/contract.mjs';
import { generateEd25519KeyPair } from '../lib/crypto.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const KEY_ID = 'evacuation-scenario-demo-2026';
const CLOSED_WAY_ID = 1462339230;
const ISSUED_AT = '2026-09-26T08:00:00Z';
const EXPIRES_AT = '2099-01-01T00:00:00Z';
const NOTICE = '合成模擬資料，不代表真實災況';

const scenario = {
  schema_version: 'evacuation-scenario-v0',
  description: 'Synthetic evacuation demo on real Neihu OSM geometry. Generated by pipeline/tools/generate-evacuation-scenario.mjs.',
  synthetic_notice: NOTICE,
  origin: { label: '西湖（內湖路一段附近）', lon: 121.566, lat: 25.081 },
  shelters: [
    { id: 'shelter:5582', name: '西湖國小', lon: 121.5657, lat: 25.0838 },
    { id: 'shelter:5593', name: '西湖國中', lon: 121.5657, lat: 25.0858 },
  ],
  closed_way_id: CLOSED_WAY_ID,
  steps: [
    { step: 1, action: 'plan route with no events', expect: 'best shelter 西湖國小, about 370 m' },
    { step: 2, action: 'receive road-closed chunk', expect: `route to 西湖國小 detours around way ${CLOSED_WAY_ID} (about 480 m); still the best shelter` },
    { step: 3, action: 'receive shelter-full chunk', expect: '西湖國小 returns no_route (SHELTER_FULL); recommendation moves to 西湖國中 (about 670 m)' },
  ],
};

const walkRoads = JSON.parse(await readFile(path.join(ROOT, 'android/app/src/main/assets/routing/walk-roads.json'), 'utf8'));
const closedWay = walkRoads.ways.find(([wayId]) => wayId === CLOSED_WAY_ID);
if (!closedWay) throw new Error(`way ${CLOSED_WAY_ID} is not in walk-roads.json; regenerate the scenario`);
const coordinates = [];
for (let i = 0; i < closedWay[2].length; i += 2) coordinates.push([closedWay[2][i], closedWay[2][i + 1]]);

const { privateKey, publicKey } = generateEd25519KeyPair();
const provenance = {
  original_source: 'evacuation-scenario-demo',
  received_at: ISSUED_AT,
  transport_source: { kind: 'local_fixture', node_id: 'evacuation-scenario' },
};

const roadClosed = signEvent({
  schema_version: 'event-v0',
  namespace: 'official.tdx',
  event_id: `road:w${CLOSED_WAY_ID}-xihu-demo`,
  event_type: 'ROAD_STATUS',
  geometry: { type: 'LineString', coordinates },
  severity: 'HIGH',
  source: 'TDX',
  source_version: 'evacuation-demo-1',
  event_version: 1,
  issued_at: ISSUED_AT,
  expires_at: EXPIRES_AT,
  attributes: {
    status: 'CLOSED',
    road_name: '西湖示範封閉路段',
    reason: 'demo',
    synthetic_notice: NOTICE,
    area_id: 'neihu.xihu',
    theme: 'road',
  },
  signing_key_id: KEY_ID,
  provenance,
}, privateKey);

const shelterFull = signEvent({
  schema_version: 'event-v0',
  namespace: 'official.fire',
  event_id: 'shelter:5582-xihu-demo',
  event_type: 'SHELTER_STATUS',
  geometry: { type: 'Point', coordinates: [121.5657, 25.0838] },
  severity: 'HIGH',
  source: 'FIRE_AGENCY',
  source_version: 'evacuation-demo-1',
  event_version: 1,
  issued_at: ISSUED_AT,
  expires_at: EXPIRES_AT,
  attributes: {
    status: 'OPEN',
    site_name: '西湖國小',
    capacity: 81,
    available: 0,
    synthetic_notice: NOTICE,
    area_id: 'neihu.xihu',
    theme: 'shelter',
  },
  signing_key_id: KEY_ID,
  provenance,
}, privateKey);

function bundle(datasetId, event) {
  const built = buildBundle([event], {
    datasetId,
    namespace: 'official',
    datasetVersion: 1,
    source: event.source,
    sourceVersion: event.source_version,
    createdAt: ISSUED_AT,
    expiresAt: EXPIRES_AT,
    signingKeyId: KEY_ID,
    privateKey,
  });
  const [chunk] = built.chunks;
  const check = verifyChunk(chunk, built.manifest, publicKey, { trustedKeyIds: [KEY_ID], now: ISSUED_AT });
  if (!check.valid) throw new Error(`${datasetId} failed self-check: ${JSON.stringify(check.errors)}`);
  return chunk;
}

const chunks = {
  'step2-road-closed.json': bundle('evacuation-demo-road', roadClosed),
  'step3-shelter-full.json': bundle('evacuation-demo-shelter', shelterFull),
};

scenario.events = [roadClosed, shelterFull];
await mkdir(path.join(ROOT, 'data/fixtures/neihu'), { recursive: true });
await writeFile(path.join(ROOT, 'data/fixtures/neihu/evacuation-scenario.json'), `${JSON.stringify(scenario, null, 2)}\n`, 'utf8');

const keyBase64 = publicKey.export({ format: 'der', type: 'spki' }).toString('base64');
for (const targetDir of ['android/app/src/main/assets', 'android/app/src/test/resources']) {
  const chunkDir = path.join(ROOT, targetDir, 'fixtures/evacuation-scenario');
  await mkdir(chunkDir, { recursive: true });
  for (const [name, chunk] of Object.entries(chunks)) {
    await writeFile(path.join(chunkDir, name), `${JSON.stringify(chunk, null, 2)}\n`, 'utf8');
  }
  const trustedKeysPath = path.join(ROOT, targetDir, 'trust/trusted-keys.json');
  const trusted = JSON.parse(await readFile(trustedKeysPath, 'utf8'));
  trusted[KEY_ID] = keyBase64;
  await writeFile(trustedKeysPath, `${JSON.stringify(trusted, null, 2)}\n`, 'utf8');
}
console.log(`wrote data/fixtures/neihu/evacuation-scenario.json and ${Object.keys(chunks).length} signed chunks; trust key "${KEY_ID}" added`);
